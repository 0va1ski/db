// Задание 3. Вариант 1.
// Сформировать квадратную матрицу порядка n по образцу:
//   1    2    3   ...  n
//   n   n-1  n-2  ...  1
//   1    2    3   ...  n
//   n   n-1  n-2  ...  1
//   ...
// Строки с нечётными номерами (1, 3, 5...) идут от 1 до n,
// строки с чётными номерами (2, 4, 6...) идут от n до 1.

#include <iostream>
#include <iomanip>
#include <cstdlib>
using namespace std;

int main() {
    system("chcp 65001 > nul");   // чтобы русские буквы нормально отображались в консоли Windows

    const int MAX_SIZE = 20;
    int Y[MAX_SIZE][MAX_SIZE];
    int n;

    // Ввод порядка матрицы
    cout << "Введите порядок матрицы n (от 1 до " << MAX_SIZE << "): ";
    cin >> n;
    while (n < 1 || n > MAX_SIZE) {
        cout << "Ошибка! n должно быть от 1 до " << MAX_SIZE << ". Введите ещё раз: ";
        cin >> n;
    }

    // Формирование матрицы по образцу
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            if (i % 2 == 0) {
                Y[i][j] = j + 1; // строка идёт от 1 до n
            } else {
                Y[i][j] = n - j; // строка идёт от n до 1
            }
        }
    }

    // Вывод матрицы (элементы главной диагонали выделены квадратными скобками)
    cout << "Матрица порядка " << n << ":" << endl;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            if (i == j) {
                cout << "[" << setw(2) << Y[i][j] << "]"; // элемент главной диагонали
            } else {
                cout << " " << setw(2) << Y[i][j] << " ";
            }
        }
        cout << endl;
    }

    return 0;
}