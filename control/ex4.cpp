// Задание 4. Вариант 1.
// Двумерный массив (число строк и столбцов задаёт пользователь):
// ввод элементов с клавиатуры, вывод массива на экран,
// сумма элементов главной диагонали.

#include <iostream>
#include <iomanip>
#include <cstdlib>
using namespace std;

int main() {
    system("chcp 65001 > nul"); // чтобы русские буквы нормально отображались в консоли Windows

    const int MAX_SIZE = 50;
    int a[MAX_SIZE][MAX_SIZE];
    int n, m;    // число строк и число столбцов
    int mode;    // 1 - показывать значения переменных циклов, 0 - не показывать
    int sum = 0; // сумма элементов главной диагонали

    cout << "Показывать значения переменных циклов? (1 - да, 0 - нет): ";
    cin >> mode;

    // Ввод размеров массива
    cout << "Введите число строк n (от 1 до " << MAX_SIZE << "): ";
    cin >> n;
    while (n < 1 || n > MAX_SIZE) {
        cout << "Ошибка! n должно быть от 1 до " << MAX_SIZE << ". Введите ещё раз: ";
        cin >> n;
    }

    cout << "Введите число столбцов m (от 1 до " << MAX_SIZE << "): ";
    cin >> m;
    while (m < 1 || m > MAX_SIZE) {
        cout << "Ошибка! m должно быть от 1 до " << MAX_SIZE << ". Введите ещё раз: ";
        cin >> m;
    }

    // Ввод элементов массива с клавиатуры
    cout << "Введите элементы массива:" << endl;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cout << "a[" << i << "][" << j << "] = ";
            cin >> a[i][j];
            if (mode == 1) {
                cout << "  [цикл ввода] i = " << i << ", j = " << j << endl;
            }
        }
    }

    // Вывод массива (элементы главной диагонали выделены квадратными скобками)
    cout << "Введённый массив:" << endl;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            if (i == j) {
                cout << "[" << setw(5) << a[i][j] << "]"; // элемент главной диагонали
            } else {
                cout << " " << setw(5) << a[i][j] << " ";
            }
        }
        if (mode == 1) {
            cout << "   [цикл вывода] i = " << i;
        }
        cout << endl;
    }

    // Сумма элементов главной диагонали
    // (если массив не квадратный, диагональ идёт до меньшего из размеров)
    int k = n;
    if (m < n) {
        k = m;
    }
    for (int i = 0; i < k; i++) {
        sum = sum + a[i][i];
        if (mode == 1) {
            cout << "[цикл суммы] i = " << i << ", a[i][i] = " << a[i][i]
                 << ", сумма = " << sum << endl;
        }
    }

    cout << "Сумма элементов главной диагонали: " << sum << endl;

    return 0;
}