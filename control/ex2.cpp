// Задание 2. Вариант 1.
// Одномерный массив натуральных чисел: ввод с клавиатуры, вывод массива
// и его же в обратном порядке, сумма и количество чётных элементов.

#include <iostream>
using namespace std;

int main() {
    system("chcp 65001 > nul");   // чтобы русские буквы нормально отображались в консоли Windows

    int a[10];        // массив на 10 элементов
    int sum = 0;      // сумма чётных элементов
    int kol = 0;      // количество чётных элементов
    int mode;         // 1 - показывать значения переменных циклов, 0 - не показывать

    cout << "Показывать значения переменных циклов? (1 - да, 0 - нет): ";
    cin >> mode;

    // Ввод массива с клавиатуры
    cout << "Введите 10 натуральных чисел:" << endl;
    for (int i = 0; i < 10; i++) {
        cout << "a[" << i << "] = ";
        cin >> a[i];
        // натуральное число должно быть больше нуля
        while (a[i] <= 0) {
            cout << "Число должно быть натуральным (больше 0). Введите ещё раз: ";
            cin >> a[i];
        }
        if (mode == 1) {
            cout << "  [цикл ввода] i = " << i << endl;
        }
    }

    // Вывод массива
    cout << "Массив: " << endl;
    for (int i = 0; i < 10; i++) {
        cout << a[i] << " ";
        if (mode == 1) {
            cout << "(i = " << i << ") " << endl;
        }
    }
    cout << endl;

    // Вывод массива в обратном порядке
    cout << "Массив в обратном порядке: " << endl;
    for (int i = 9; i >= 0; i--) {
        cout << a[i] << " ";
        if (mode == 1) {
            cout << "(i = " << i << ") " << endl;
        }
    }
    cout << endl;

    // Сумма и количество чётных элементов
    for (int i = 0; i < 10; i++) {
        if (a[i] % 2 == 0) {
            sum = sum + a[i];
            kol = kol + 1;
        }
        if (mode == 1) {
            cout << "[цикл подсчёта] i = " << i << ", a[i] = " << a[i]
                 << ", сумма = " << sum << ", количество = " << kol << endl;
        }
    }

    cout << "Сумма чётных элементов: " << sum << endl;
    cout << "Количество чётных элементов: " << kol << endl;

    return 0;
}